// This is a single-line comment
// It starts with two forward slashes and continues to the end of the line

/*
This is a multi-line comment.
It can span multiple lines.
Everything between the opening and closing markers is ignored.
*/

console.log("Comments in JavaScript:");

// Single-line comment example
let userName = "Alice"; // This variable stores the user's name

// Multi-line comment example
/*
The following code logs a greeting message.
It uses the userName variable defined above.
*/
console.log("Hello, " + userName + "!");

/*
Multi-line comments can also be used for:
- Explaining complex logic
- Temporarily disabling code blocks
- Adding copyright or license information
*/

// You can use single-line comments for short notes
// Like this one explaining the next line
let age = 25; // Age in years

// Comments are ignored during execution, so they don't affect performance
console.log("User age: " + age);